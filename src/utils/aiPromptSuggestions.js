function deepFreeze(value) {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    Object.getOwnPropertyNames(value).forEach((prop) => deepFreeze(value[prop]));
    Object.freeze(value);
  }
  return value;
}

