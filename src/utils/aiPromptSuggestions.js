function normalizeSurfaceKey(surfaceKey) {
  if (typeof surfaceKey !== 'string') return '';
  const trimmed = surfaceKey.trim();
  return trimmed.startsWith(WIDGET_SURFACE_PREFIX)
    ? trimmed.slice(WIDGET_SURFACE_PREFIX.length)
    : trimmed;
}

function safeText(value) {
  return typeof value === 'string' && value.trim().length > 0 ? value.trim() : '';
}

// Builds one optional, additive suggestion from caller-supplied context facts.
// Only echoes back values the caller already provided (never invents dates,
// names, or attributions), so it stays consistent with the safety rules.
function buildContextualSuggestion(surfaceKey, actionKey, context) {
  switch (surfaceKey) {
    case 'news': {
      const language = safeText(context.sourceLanguage);
      if (language && (!actionKey || actionKey === 'translate')) {
        return `תרגם וסכם בעברית את המבזק שסופק בשפת המקור (${language}), בלי להוסיף עובדות חדשות.`;
      }
      return '';
    }
    case 'polls': {
      const question = safeText(context.activeQuestion);
      if (question && (!actionKey || actionKey === 'rewrite' || actionKey === 'rewrite-bias')) {
        return `שכתב בניסוח ניטרלי וברור את השאלה הקיימת "${question}" ושמור את כל נתוני ההצבעה כפי שהם.`;
      }
      return '';
    }
    case 'events': {
      const month = safeText(context.monthLabel);
      if (month && (!actionKey || actionKey === 'reuse')) {
        return `התאם מחודש ${month} הקודם את רשימת האירועים לחודש הנוכחי, כולל רק תאריכים שתספק בפועל.`;
      }
      return '';
    }
    case 'countdown': {
      const label = safeText(context.eventLabel);
      if (label && (!actionKey || actionKey === 'event')) {
        return `צור יעד ספירה לאחור עבור "${label}" רק לאחר שתציין את התאריך והשעה המדויקים.`;
      }
      return '';
    }
    default:
      return '';
  }
}

function withContextualSuggestion(surfaceKey, actionKey, baseList, context) {
  if (!context || typeof context !== 'object') return baseList.slice();
  const extra = buildContextualSuggestion(surfaceKey, actionKey, context);
  return extra ? [extra, ...baseList] : baseList.slice();
}

// Resolves which registry entry should back a normalized surface key.
// - A surface with its own entry (every ADMIN_AI_CAPABILITIES key, plus the
//   standalone "org-chart-import") always wins.
// - A key that IS a recognized ADMIN_AI_CAPABILITIES tab but has no entry here
//   safely falls back to the generic "ai-help" pool instead of showing nothing.
// - Anything else (typos, removed tabs, garbage input) is not a known surface,
//   so it returns undefined and callers get an empty list rather than a guess.
function resolveSuggestionEntry(normalizedSurface) {
  const ownEntry = AI_PROMPT_SUGGESTIONS[normalizedSurface];
  if (ownEntry) return ownEntry;

  const isKnownAdminCapability = Object.prototype.hasOwnProperty.call(
    ADMIN_AI_CAPABILITIES,
    normalizedSurface
  );
  if (isKnownAdminCapability) return AI_PROMPT_SUGGESTIONS[AI_HELP_FALLBACK_SURFACE];

  return undefined;
}

/**
 * Resolves the list of example Hebrew prompts for a given AI surface/action.
 *
 * `surfaceKey` may be a raw ADMIN_AI_CAPABILITIES key (e.g. "news"), a
 * "widget:<id>" key (e.g. "widget:news", used by AdminWidgetAIAssistant), or
 * the standalone "org-chart-import" surface. When `actionKey` matches a
 * configured action-specific pool, that pool is preferred; otherwise the
 * surface's default pool is used. A surface key that is a recognized
 * ADMIN_AI_CAPABILITIES tab without its own authored prompts falls back to
 * the generic "ai-help" pool; any other unknown surface resolves to an empty
 * list rather than guessing.
 *
 * @param {string} surfaceKey
 * @param {string} [actionKey]
 * @param {object} [context] - optional, surface-specific supplied facts (e.g.
 *   { sourceLanguage }, { activeQuestion }, { monthLabel }, { eventLabel }).
 * @returns {string[]} A fresh array of suggestion strings (never mutated in place).
 */
export function getAiPromptSuggestions(surfaceKey, actionKey, context) {
  const normalizedSurface = normalizeSurfaceKey(surfaceKey);
  const entry = resolveSuggestionEntry(normalizedSurface);
  if (!entry) return [];

  const actionList = actionKey && entry.actions ? entry.actions[actionKey] : undefined;
  const baseList = Array.isArray(actionList) && actionList.length > 0 ? actionList : entry.default;

  return withContextualSuggestion(normalizedSurface, actionKey, baseList, context);
}

/**
 * Picks one suggestion from `options` without repeating `previousSuggestion`
 * when at least two options are available. Never mutates `options`.
 *
 * @param {string[]} options
 * @param {string} [previousSuggestion]
 * @param {() => number} [random] - injectable RNG (defaults to Math.random) for deterministic tests.
 * @returns {string} The chosen suggestion, or '' when no option is available.
 */
export function pickAiPromptSuggestion(options, previousSuggestion, random = Math.random) {
  const pool = Array.isArray(options)
    ? options.filter((option) => typeof option === 'string' && option.trim().length > 0)
    : [];

  if (pool.length === 0) return '';
  if (pool.length === 1) return pool[0];

  const candidates = previousSuggestion
    ? pool.filter((option) => option !== previousSuggestion)
    : pool;
  const effectiveCandidates = candidates.length > 0 ? candidates : pool;

  const randomValue = Number(random());
  const safeRandomValue = Number.isFinite(randomValue) ? randomValue : 0;
  const index = Math.min(
    effectiveCandidates.length - 1,
    Math.max(0, Math.floor(safeRandomValue * effectiveCandidates.length))
  );
  return effectiveCandidates[index];
}

